/**
 * 取得 YouTube embed URL
 */
export function getYouTubeEmbedUrl(videoId, startTime = null) {
  let url = `https://www.youtube.com/embed/${videoId}`;
  if (startTime) {
    url += `?start=${startTime}`;
  }
  return url;
}

/**
 * 取得 YouTube watch URL
 */
export function getYouTubeWatchUrl(videoId) {
  return `https://www.youtube.com/watch?v=${videoId}`;
}

/**
 * 取得影片的完整資訊（包含頻道資訊）
 * @param {string} videoId - 影片的 id（例如：'doubles-rotation-concepts'）
 */
export function getVideoInfo(videoId) {
  const video = videos[videoId];
  if (!video) return null;
  
  const channel = channels[video.channelId];
  return {
    ...video,
    channel: channel || null,
    embedUrl: getYouTubeEmbedUrl(video.videoId),
    watchUrl: getYouTubeWatchUrl(video.videoId)
  };
}

